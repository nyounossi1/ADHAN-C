#!/usr/bin/env python3
"""Generate src/QrHelp.h: the QR code for the Prayer Calculation help short link (AD-51).

Needs the 'segno' package (pip install segno). The URL never changes at runtime, so the
bitmap is stored in flash and no QR library is linked into the firmware.
Usage: python3 scripts/gen_qr_help.py [url]
"""
import os, sys
import segno

URL = sys.argv[1] if len(sys.argv) > 1 else "https://adhanai.com/pc"
q = segno.make(URL, error="M", boost_error=False)
n = q.symbol_size(border=0)[0]
assert n <= 32, "QR too large for 32-bit row storage"
rows = []
for r in q.matrix:
    v = 0
    for bit in r:
        v = (v << 1) | (1 if bit else 0)
    rows.append(v)

out = os.path.join(os.path.dirname(__file__), "..", "src", "QrHelp.h")
with open(out, "w") as f:
    f.write("// Generated by scripts/gen_qr_help.py - do not edit.\n")
    f.write("// QR code for %s (version %d, ECC M), one row per entry, MSB = leftmost module.\n" % (URL, q.version))
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("#define QR_HELP_SIZE %d\n" % n)
    f.write("static const uint32_t QR_HELP_ROWS[QR_HELP_SIZE] = {\n")
    for v in rows:
        f.write("  0x%08XU,\n" % v)
    f.write("};\n")
print("wrote", out, "size", n)
